// Regenerates TODO.md from the actual "[TODO ...]" markers in the content,
// plus the list of images each case study expects (and whether each exists yet).
//
//   npm run todos
//
// No dependencies. Run it whenever you've filled things in; finished items disappear.
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, extname, basename } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const TODO_RE = /\[TODO[^\]]*\]/g;
const rel = (p) => p.replace(root, '');

function todosIn(file) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const out = [];
  let section = '';
  lines.forEach((line, i) => {
    const h = line.match(/^#{2,3}\s+(.*)/);
    if (h) section = h[1].trim();
    if (/^\s*(\/\/|\*|\/\*)/.test(line) && !line.includes("'[TODO") && !line.includes('"[TODO')) return; // skip code comments
    // TODOs inside alt="" / note="" are covered by the image list below.
    const skip = [...line.matchAll(/(alt|note)="[^"]*"/g)].map((a) => [a.index, a.index + a[0].length]);
    for (const m of line.matchAll(TODO_RE)) {
      if (skip.some(([a, b]) => m.index > a && m.index < b)) continue;
      const where = section || (line.match(/^\s*([a-zA-Z]+):/)?.[1] ?? '');
      out.push({ line: i + 1, text: m[0], where });
    }
  });
  return out;
}

function imagesIn(file) {
  const src = readFileSync(file, 'utf8');
  const found = [];
  const cover = src.match(/^cover:\s*(.+)$/m);
  const coverNote = src.match(/^coverNote:\s*(.+)$/m);
  if (cover) found.push({ file: cover[1].trim(), note: coverNote?.[1].trim() ?? 'Cover image' });
  for (const m of src.matchAll(/<(?:Figure|FlowStep|IterationStage)\b([\s\S]*?)\/?>/g)) {
    const attrs = m[1];
    const f = attrs.match(/file="([^"]+)"/);
    const n = attrs.match(/note="([^"]+)"/);
    if (f && !found.some((x) => x.file === f[1])) found.push({ file: f[1], note: n?.[1] ?? '' });
  }
  return found;
}

const imgRoot = join(root, 'src/assets/images');
function imageExists(file) {
  const dir = join(imgRoot, file.split('/').slice(0, -1).join('/'));
  if (!existsSync(dir)) return false;
  const stem = basename(file, extname(file)).toLowerCase();
  return readdirSync(dir).some((f) => basename(f, extname(f)).toLowerCase() === stem);
}

const projectsDir = join(root, 'src/content/projects');
const projects = readdirSync(projectsDir).filter((f) => /\.mdx?$/.test(f)).sort();

let md = `# TODO\n\nGenerated by \`npm run todos\` from the markers in the content. Don't edit by hand: fill in the marker in the source file and re-run.\n\nEvery \`[TODO ...]\` marker is highlighted on the page in \`npm run dev\` and automatically removed from the production build (GitHub Pages).\n\n`;

// --- Setup items
md += `## Setup\n\n`;
const cfg = readFileSync(join(root, 'astro.config.mjs'), 'utf8');
md += `- [${cfg.includes('USERNAME') ? ' ' : 'x'}] \`astro.config.mjs\`: set \`site\` to your GitHub Pages URL (replace USERNAME)\n`;
const cvSize = statSync(join(root, 'public/cv.pdf')).size;
md += `- [${cvSize < 5000 ? ' ' : 'x'}] \`public/cv.pdf\`: replace the placeholder with your real CV (same file name)\n\n`;

// --- Content markers
md += `## Content markers\n\n`;
const sources = [...projects.map((f) => join(projectsDir, f)), join(root, 'src/data/site.ts')];
let total = 0;
for (const file of sources) {
  const items = todosIn(file);
  if (!items.length) continue;
  total += items.length;
  md += `### ${rel(file)} (${items.length})\n\n`;
  for (const t of items) md += `- [ ] L${t.line}${t.where ? ` · ${t.where}` : ''}: ${t.text.replace(/^\[TODO:?\s*/, '').replace(/\]$/, '')}\n`;
  md += `\n`;
}

// --- Images
md += `## Images to export\n\nDrop files into \`src/assets/images/<project>/\` using these names (any of .png .jpg .webp works). The placeholder is replaced automatically and Astro generates AVIF/WebP at several sizes. Export at 2× (e.g. 2400px wide for full-width images). Alt text lives next to each image in the .mdx file: check it describes what's actually on screen.\n\n`;
let missing = 0;
for (const f of projects) {
  const imgs = imagesIn(join(projectsDir, f));
  const done = imgs.filter((i) => imageExists(i.file)).length;
  missing += imgs.length - done;
  md += `### ${f.replace(/\.mdx?$/, '')} (${done}/${imgs.length} added)\n\n`;
  for (const i of imgs) md += `- [${imageExists(i.file) ? 'x' : ' '}] \`${i.file}\`${i.note ? ` · ${i.note}` : ''}\n`;
  md += `\n`;
}

md = md.replace('# TODO\n\n', `# TODO\n\n**${total} content markers · ${missing} images still missing**\n\n`);
writeFileSync(join(root, 'TODO.md'), md);
console.log(`TODO.md updated: ${total} content markers, ${missing} images missing.`);
